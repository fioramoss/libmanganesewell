#include <string>
#include <vector>

void greatest_divisor() {
    int a = 48, b = 18;
    while (b != 0) {
        int t = a % b;
        a = b;
        b = t;
    }
    (void)a;
}

void sum_squares() {
    int acc = 0;
    for (int i = -5; i <= 5; ++i) acc += i * i;
    (void)acc;
}

void product_range() {
    int acc = 1;
    for (int i = 1; i <= 5; ++i) acc *= i;
    (void)acc;
}

void sum_pair() {
    int left = 3;
    int right = 9;
    int total = left + right;
    (void)total;
}

extern "C" int hidden_compass();
extern "C" void gentle_willow();
extern "C" void ivory_vale();

int main() {
    greatest_divisor();
    sum_squares();
    product_range();
    sum_pair();
    gentle_willow();
    ivory_vale();
    return hidden_compass();
}
